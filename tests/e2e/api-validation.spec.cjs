test('a running test shows its progress and can be cancelled without storing anything', async ({ page }) => {
  let release = () => undefined
  const held = new Promise((resolve) => { release = resolve })
  await page.route('**/api/test-api', async (route) => {
    await held
    await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(VALID) }).catch(() => undefined)
  })
  await open(page)
  await add(page, 'Consulta API')
  const panel = panelOf(page)
  await page.getByLabel('URL da API', { exact: true }).fill(API)
  await button(page, 'Validar API').click()
  await button(page, 'Testar API').click()
  await expect(button(page, 'Testando a API')).toHaveAttribute('aria-disabled', 'true')
  await expect(button(page, 'Testando a API')).toBeFocused()
  await expect(panel.locator('form[aria-busy="true"]')).toHaveCount(1)
  await expect(said(page, 'Validar API')).toHaveText('Testando a API.')
  await button(page, 'Cancelar teste').click()
  await expect(button(page, 'Testar API')).toBeFocused()
  await expect(said(page, 'Validar API')).toHaveText('Teste cancelado.')
  await expect(panel.locator('form[aria-busy="true"]')).toHaveCount(0)
  release()
  await expect(heading(page, 'Validar API')).toBeVisible()
  const data = await dataOf(page, '4')
  expect([data.isApiValidated, data.validated_signature, 'api_test_values' in data]).toEqual([false, '', false])
  await expect(heading(page, 'API validada')).toHaveCount(0)
})
